import type { ImageEntry } from "@/lib/image-manifest";

const basePath = process.env.NEXT_PUBLIC_BASE_PATH ?? "";

export type PictureViewProps = {
  /** Path of the original under public/, e.g. "/infographics/infographics_1.jpeg". */
  src: string;
  alt: string;
  /** The rendered width at each breakpoint, so the browser picks the right file. */
  sizes: string;
  className?: string;
  loading?: "eager" | "lazy";
  fetchPriority?: "high" | "low" | "auto";
  onClick?: React.MouseEventHandler<HTMLImageElement>;
};

/**
 * Responsive <picture>: AVIF, then WebP, then the original JPEG, each at the
 * widths generated by scripts/generate-image-manifest.mjs. Width and height
 * come from the manifest, so the layout reserves space before the image loads.
 *
 * Images missing from the manifest render as a plain <img>, so new artwork
 * never breaks the page — it just is not optimised until the next build.
 */
export function PictureView({
  src,
  entry,
  alt,
  sizes,
  className,
  loading = "lazy",
  fetchPriority,
  onClick,
}: PictureViewProps & { entry: ImageEntry | null }) {
  const fallback = `${basePath}${src}`;

  if (!entry) {
    // eslint-disable-next-line @next/next/no-img-element
    return <img src={fallback} alt={alt} className={className} loading={loading} decoding="async" onClick={onClick} />;
  }

  const srcSet = (variants: { width: number; src: string }[]) =>
    variants.map((variant) => `${basePath}${variant.src} ${variant.width}w`).join(", ");

  return (
    <picture>
      <source type="image/avif" srcSet={srcSet(entry.variants.avif)} sizes={sizes} />
      <source type="image/webp" srcSet={srcSet(entry.variants.webp)} sizes={sizes} />
      <img
        src={fallback}
        alt={alt}
        width={entry.width}
        height={entry.height}
        sizes={sizes}
        loading={loading}
        decoding="async"
        fetchPriority={fetchPriority}
        className={className}
        onClick={onClick}
      />
    </picture>
  );
}
