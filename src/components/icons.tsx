/**
 * The site's icon set: a dozen strokes, drawn inline so they inherit
 * `currentColor`, scale with text, and need no icon library. Replaces emoji
 * (🛡) and Unicode arrows (↗ →), which render differently on every platform
 * and are read aloud by screen readers.
 *
 * Every icon is decorative (aria-hidden). Put the meaning in visible text or
 * an aria-label on the control, never in the icon.
 */

type IconProps = { className?: string };

function Svg({ className = "h-4 w-4", children }: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      aria-hidden="true"
      focusable="false"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      className={`shrink-0 ${className}`}
    >
      {children}
    </svg>
  );
}

