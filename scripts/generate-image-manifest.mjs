/**
 * Writes src/lib/image-manifest.ts with the intrinsic pixel size of every
 * poster in public/infographics and public/comics.
 *
 * Static export forces `images.unoptimized`, so Next cannot infer dimensions
 * for us. Without width/height the gallery reflows as each ~250KB JPEG lands.
 * Runs from `prebuild`, so adding a poster keeps the manifest correct with no
 * extra step.
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SOURCE_DIRS = ["infographics", "comics"];
const OUTPUT = "src/lib/image-manifest.ts";

/** Reads width/height from a JPEG's start-of-frame marker. */
function readJpegSize(buffer) {
  let offset = 2;

  while (offset < buffer.length) {
    if (buffer[offset] !== 0xff) {
      offset += 1;
      continue;
    }

    const marker = buffer[offset + 1];
    const isStartOfFrame =
      marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc;

    if (isStartOfFrame) {
      return { height: buffer.readUInt16BE(offset + 5), width: buffer.readUInt16BE(offset + 7) };
    }

    offset += 2 + buffer.readUInt16BE(offset + 2);
  }

  return null;
}

const entries = [];

for (const dir of SOURCE_DIRS) {
  const files = readdirSync(join("public", dir))
    .filter((file) => /\.jpe?g$/i.test(file))
    .sort();

  for (const file of files) {
    const size = readJpegSize(readFileSync(join("public", dir, file)));

    if (!size) {
      console.warn(`Could not read dimensions for ${dir}/${file} — skipping.`);
      continue;
    }

    entries.push([`/${dir}/${file}`, size]);
  }
}

const body = entries
  .map(([path, size]) => `  "${path}": { width: ${size.width}, height: ${size.height} },`)
  .join("\n");

writeFileSync(
  OUTPUT,
  `// Generated by scripts/generate-image-manifest.mjs — do not edit by hand.\n\n` +
    `export const imageDimensions: Record<string, { width: number; height: number }> = {\n` +
    `${body}\n};\n\n` +
    `export function getImageDimensions(src: string) {\n` +
    `  return imageDimensions[src] ?? null;\n` +
    `}\n`,
  "utf8",
);

console.log(`Wrote ${OUTPUT} with ${entries.length} images.`);
